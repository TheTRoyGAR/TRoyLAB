export type ContactStatus = 'lead' | 'prospect' | 'customer' | 'vip';
export type ContactSource = 'website' | 'referral' | 'social' | 'direct';

export interface Contact {
  id: string;
  firstName: string;
  lastName: string;
  email: string;
  phone: string;
  country: string;
  status: ContactStatus;
  source: ContactSource;
  totalSpent: number;
  bookingsCount: number;
  lastContact: string;
  tags: string[];
  notes: string;
  createdAt: string;
}

export type BookingStatus =
  | 'inquiry'
  | 'quoted'
  | 'confirmed'
  | 'deposit_paid'
  | 'fully_paid'
  | 'cancelled';

export interface Booking {
  id: string;
  contactId: string;
  packageName: string;
  destination: string;
  departureDate: string;
  returnDate: string;
  travelers: { adults: number; children: number };
  totalAmount: number;
  status: BookingStatus;
  createdAt: string;
  agentNotes: string;
  requiresOwnerApproval: boolean;
}

export type LeadStage =
  | 'new'
  | 'contacted'
  | 'qualified'
  | 'proposal_sent'
  | 'negotiating'
  | 'closed_won'
  | 'closed_lost';

export interface Lead {
  id: string;
  contactId: string;
  packageInterest: string;
  estimatedValue: number;
  stage: LeadStage;
  probability: number;
  expectedClose: string;
  assignedTo: string;
  lastActivity: string;
}

